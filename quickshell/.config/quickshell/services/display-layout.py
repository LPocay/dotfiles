#!/usr/bin/env python3
"""Read and persist Hyprland monitor placement through its Lua IPC API."""
import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import time


STATE = Path(os.environ.get('XDG_STATE_HOME', str(Path.home() / '.local/state'))) / 'quickshell'
NAME = re.compile(r'[A-Za-z0-9_.:-]+\Z')


def run(*args):
    result = subprocess.run(args, capture_output=True, text=True, timeout=8)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or 'Hyprland command failed.')
    return result.stdout


def snapshot():
    data = json.loads(run('hyprctl', 'monitors', '-j'))
    if not isinstance(data, list):
        raise ValueError('Invalid monitor information.')
    monitors = []
    for m in data:
        if m.get('disabled') or m.get('mirrorOf', 'none') not in ('none', '', None):
            continue
        if not NAME.fullmatch(m['name']):
            raise ValueError('Unsupported monitor name.')
        for key in ('width', 'height', 'scale', 'refreshRate'):
            if not isinstance(m.get(key), (int, float)) or not math.isfinite(m[key]) or m[key] <= 0:
                raise ValueError('Invalid monitor dimensions or mode.')
        m.setdefault('transform', 0)
        monitors.append(m)
    if not monitors:
        raise ValueError('No active monitors available.')
    return monitors


def saved():
    try:
        return json.loads((STATE / 'display-layout.json').read_text())
    except FileNotFoundError:
        return {}


def dimensions(m):
    w, h = m['width'], m['height']
    if m['transform'] % 2:
        w, h = h, w
    return math.floor(w / m['scale'] + 0.5), math.floor(h / m['scale'] + 0.5)


def validate(request, monitors):
    if not isinstance(request, dict):
        raise ValueError('Invalid layout request.')
    entries = request.get('monitors')
    if not isinstance(entries, list) or len(entries) != len(monitors) or not all(isinstance(e, dict) for e in entries):
        raise ValueError('Connected monitors changed. Refresh before applying.')
    names = [m.get('name') for m in entries]
    if len(set(names)) != len(names) or set(names) != {m['name'] for m in monitors}:
        raise ValueError('Connected monitors changed. Refresh before applying.')
    if request.get('primary') not in names:
        raise ValueError('Select a connected primary monitor.')
    for entry in entries:
        for key in ('x', 'y'):
            value = entry.get(key)
            if type(value) is not int or abs(value) > 32768:
                raise ValueError('Positions must be whole numbers between -32768 and 32768.')
    positions = {e['name']: e for e in entries}
    placed = [dict(m, x=positions[m['name']]['x'], y=positions[m['name']]['y']) for m in monitors]
    for i, a in enumerate(placed):
        aw, ah = dimensions(a)
        for b in placed[i + 1:]:
            bw, bh = dimensions(b)
            if min(a['x'] + aw, b['x'] + bw) > max(a['x'], b['x']) and min(a['y'] + ah, b['y'] + bh) > max(a['y'], b['y']):
                raise ValueError('Monitors overlap. Drag them apart or use the placement buttons.')
    return placed


def lua(monitors, primary):
    # Names are restricted above; numeric mode values come from a fresh IPC snapshot.
    lines = ['-- Generated by Quickshell display settings.']
    for m in monitors:
        mode = f"{m['width']}x{m['height']}@{m['refreshRate']}"
        fields = ['output = "%s"' % m['name'], 'mode = "%s"' % mode,
                  'position = "%sx%s"' % (m['x'], m['y']), 'scale = %s' % m['scale'],
                  'transform = %s' % m['transform']]
        # A new monitor rule replaces the previous one, including color options.
        for source, target in [('sdrBrightness', 'sdrbrightness'), ('sdrSaturation', 'sdrsaturation'),
                               ('sdrMinLuminance', 'sdr_min_luminance'), ('sdrMaxLuminance', 'sdr_max_luminance')]:
            value = m.get(source)
            if type(value) in (int, float) and math.isfinite(value):
                fields.append('%s = %s' % (target, value))
        cm = m.get('colorManagementPreset', '')
        if re.fullmatch(r'[A-Za-z0-9_-]+', cm):
            fields.append('cm = "%s"' % cm)
        if 'vrr' in m:
            fields.append('vrr = %d' % bool(m['vrr']))
        if 'currentFormat' in m:
            fields.append('bitdepth = %d' % (10 if '2101010' in m['currentFormat'] else 8))
        lines.append('hl.monitor({ ' + ', '.join(fields) + ' })')
    lines.append('hl.config({ cursor = { default_monitor = "%s" } })' % primary)
    return '\n'.join(lines) + '\n'


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def evaluate(code):
    # hyprctl parses every argument beginning with "--" as a CLI option,
    # including a Lua chunk that starts with our generated-file comment.
    response = run('hyprctl', 'eval', 'do\n' + code + '\nend')
    if response.strip().lower() != 'ok':
        raise ValueError(response.strip() or 'Could not apply the monitor layout.')


def verify_positions(monitors):
    expected = {m['name']: (m['x'], m['y']) for m in monitors}
    # Monitor rules can settle after the eval reply. Bound retries to avoid
    # rejecting a successful asynchronous layout update or flooding the IPC.
    for attempt in range(5):
        actual = snapshot()
        if {m['name']: (m['x'], m['y']) for m in actual} == expected:
            return
        if attempt < 4:
            time.sleep(0.1)
    raise ValueError('Monitor layout changed or could not be applied. Refresh and try again.')


def xprimary(name):
    if not os.environ.get('DISPLAY'):
        return ''
    if not shutil.which('xrandr'):
        return 'Layout saved; install xrandr to set the primary monitor for X11 applications.'
    try:
        run('xrandr', '--output', name, '--primary')
    except (ValueError, subprocess.TimeoutExpired):
        return 'Layout saved; could not set the primary monitor for X11 applications.'
    return ''


def apply(request):
    before = snapshot()
    placed = validate(request, before)
    primary = request['primary']
    previous = saved()
    old_primary = previous.get('primary')
    if old_primary not in {m['name'] for m in before}:
        old_primary = next((m['name'] for m in before if m.get('focused')), before[0]['name'])
    old_lua = lua(before, old_primary)
    new_lua = lua(placed, primary)
    previous_files = {name: (STATE / name).read_text() if (STATE / name).exists() else None
                      for name in ('display-layout.lua', 'display-layout.json')}
    try:
        evaluate(new_lua)
        verify_positions(placed)
        # Keep rules for disconnected outputs so reconnecting restores their placement.
        connected = {m['name'] for m in placed}
        persisted = [m for m in previous.get('monitors', []) if m['name'] not in connected] + placed
        atomic_write(STATE / 'display-layout.lua', lua(persisted, primary))
        atomic_write(STATE / 'display-layout.json', json.dumps({'primary': primary, 'monitors': persisted}))
    except Exception as error:
        try:
            evaluate(old_lua)
            verify_positions(before)
            for name, content in previous_files.items():
                if content is None:
                    (STATE / name).unlink(missing_ok=True)
                else:
                    atomic_write(STATE / name, content)
        except (OSError, ValueError, subprocess.TimeoutExpired):
            raise ValueError(str(error) + ' Could not fully restore the previous layout. Refresh to inspect the current positions.')
        raise
    # Native apps follow focus; Xwayland also exposes an explicit primary output.
    warning = xprimary(primary)
    try:
        response = run('hyprctl', 'dispatch', 'hl.dsp.focus({ monitor = "%s" })' % primary)
        if response.strip().lower() != 'ok':
            raise ValueError('Could not focus the primary monitor.')
    except (ValueError, subprocess.TimeoutExpired):
        warning = (warning + ' Could not focus the primary monitor.').strip()
    return {'warning': warning}


def main():
    action = sys.argv[1] if len(sys.argv) > 1 else ''
    if action == 'scan':
        monitors = snapshot()
        primary = saved().get('primary')
        if primary not in {m['name'] for m in monitors}:
            primary = next((m['name'] for m in monitors if m.get('focused')), monitors[0]['name'])
        return {'monitors': monitors, 'primary': primary}
    if action == 'apply':
        return apply(json.loads(sys.argv[2]))
    if action == 'restore-primary':
        primary = saved().get('primary')
        if primary and NAME.fullmatch(primary) and primary in {m['name'] for m in snapshot()}:
            return {'warning': xprimary(primary)}
        return {}
    raise ValueError('Usage: display-layout.py scan | apply JSON | restore-primary')


if __name__ == '__main__':
    try:
        print(json.dumps(main()))
    except (ValueError, KeyError, TypeError, OSError, subprocess.TimeoutExpired) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
